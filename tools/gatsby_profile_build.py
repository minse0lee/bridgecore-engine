def clip(s, n):
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 1] + "…"


def main():
    src = {}
    for line in open(SRC, encoding="utf-8"):
        r = json.loads(line)
        src[r["id"]] = r

    missing = [i for _, ls in PROFILE for _, ids, _ in ls for i in ids if i not in src]
    if missing:
        sys.exit(f"근거 문장 번호가 원문에 없음: {missing}")

    # 1) 엔진 입력용
    out = ["[작품 프로필] 위대한 개츠비 (F. Scott Fitzgerald, 1925) — 중간 판 v0, 사람 확인 전", "", HEADER, ""]
    for n, (title, ls) in enumerate(PROFILE, 1):
        out.append(f"{n}. {title}")
        for text, _, note in ls:
            out.append(f"- {text}" + (" (추정)" if note == "추정" else ""))
        out.append("")
    engine = "\n".join(out).rstrip() + "\n"
    (ROOT / "data/book/gatsby/profile/gatsby_profile_mid_v0.md").write_text(engine, encoding="utf-8")

    # 2) 근거 표
    rows = ["line\tsection\tnote\tevidence\ttext"]
    k = 0
    for title, ls in PROFILE:
        for text, ids, note in ls:
            k += 1
            rows.append(f"{k}\t{title}\t{note}\t{','.join(ids)}\t{text}")
    (ROOT / "data/book/gatsby/profile/gatsby_profile_mid_v0_evidence.tsv").write_text("\n".join(rows) + "\n", encoding="utf-8")

    # 3) 사람 확인용
    n_lines = k
    n_ev = sum(1 for _, ls in PROFILE for _, ids, note in ls if ids and note == "")
    n_guess = sum(1 for _, ls in PROFILE for _, _, note in ls if note == "추정")
    n_guide = sum(1 for _, ls in PROFILE for _, _, note in ls if note == "안내")
    md = [
        "---",
        'title: "《위대한 개츠비》 번역 프로필 — 중간 판 (근거 문장 포함)"',
        'subtitle: "검증엔진 입력용 · 사람 확인 전"',
        'date: "2026-11-28"',
        "---",
        "",
        "# 1. 이 문서가 무엇인가",
        "",
        "- 검증엔진이 문장을 판정할 때 함께 받는 작품 프로필의 **중간 판**입니다. 상세 판(약 4,500자)에서 단역 이름과 장별 줄거리를 뺐습니다.",
        f"- 프로필은 모두 {n_lines}줄입니다. 원문 문장을 근거로 댄 줄 {n_ev}줄, 원문에서 계산하거나 미루어 본 **추정** {n_guess}줄, 사실이 아닌 안내 문장 {n_guide}줄입니다.",
        "- 줄마다 근거가 된 원문 문장의 번호와 원문, 현재 번역을 붙였습니다. 현재 번역은 읽기 편하라고 붙인 것이고, 번역이 틀렸을 수 있으니 근거는 원문입니다.",
        "- 엔진에는 프로필 줄만 들어갑니다. 문장 번호와 근거 문장은 들어가지 않습니다.",
        f"- 엔진 입력 분량은 {len(engine):,}자입니다.",
        "",
        "# 2. 엔진에 들어가는 머리말",
        "",
        HEADER,
        "",
        "# 3. 프로필 (줄 번호와 근거 문장 번호)",
        "",
        "대괄호 안은 근거 문장 번호입니다. 근거 문장의 원문과 현재 번역은 4장에 있습니다.",
        "",
    ]
    k = 0
    for n, (title, ls) in enumerate(PROFILE, 1):
        md.append(f"## 3.{n} {title}")
        md.append("")
        for text, ids, note in ls:
            k += 1
            tag = {"추정": " **(추정)**", "안내": " (안내 문장)"}.get(note, "")
            ev = f" [{', '.join(ids)}]" if ids else ""
            md.append(f"{k}. {text}{tag}{ev}")
        md.append("")
    md += ["# 4. 줄별 근거 문장", ""]
    k = 0
    for title, ls in PROFILE:
        for text, ids, note in ls:
            k += 1
            if not ids:
                continue
            tag = " (추정)" if note == "추정" else ""
            md.append(f"**{k}번 줄{tag}**")
            md.append("")
            for i in ids:
                md.append(f"- {i}: {clip(src[i]['en'], 200)}")
                md.append(f"    - 현재 번역: {clip(src[i]['mt'], 120)}")
            md.append("")
    (ROOT / "reports/gatsby_profile_mid_2026-11-28.md").write_text("\n".join(md), encoding="utf-8")
    print(f"줄 {n_lines} (근거 {n_ev}, 추정 {n_guess}, 안내 {n_guide}), 엔진 입력 {len(engine)}자")


if __name__ == "__main__":
    main()
